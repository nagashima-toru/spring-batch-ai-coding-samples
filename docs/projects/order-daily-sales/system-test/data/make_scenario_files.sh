#!/usr/bin/env bash
# シナリオ No.1〜5 用の入力ファイルを $ST_IN / $ST_WORK に作る。No.6 用の10万件は gen_orders.sh を直接使う。
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
source "$here/env.sh"
H="order_no,line_no,order_date,store_code,item_code,quantity,unit_price"

# No.1: 2026-10-11 の正常ファイル（既定パス orders_20261011.csv）。3店舗・12明細（受注8件）
cat > "$ST_IN/orders_20261011.csv" <<CSV
$H
A0001,1,2026-10-11,S001,I0001,2,500
A0001,2,2026-10-11,S001,I0002,1,1200
A0002,1,2026-10-11,S002,I0001,3,500
A0003,1,2026-10-11,S001,I0003,10,80
A0003,2,2026-10-11,S001,I0004,1,0
A0003,3,2026-10-11,S001,I0005,999999,999999999
A0004,1,2026-10-11,S003,I0002,5,1200
A0005,1,2026-10-11,S002,I0006,1,3000
A0005,2,2026-10-11,S002,I0007,2,150
A0006,1,2026-10-11,S003,I0001,1,500
A0007,1,2026-10-11,S001,I0008,4,250
A0008,1,2026-10-11,S002,I0009,6,300
CSV

# No.2: 2026-10-12。不正行3件（数量が文字列・対象日違い・重複キー）を含むファイルと訂正後ファイル
cat > "$ST_WORK/orders_20261012_bad.csv" <<CSV
$H
B0001,1,2026-10-12,S001,I0001,2,500
B0001,2,2026-10-12,S001,I0002,abc,1200
B0002,1,2026-10-11,S002,I0001,3,500
B0003,1,2026-10-12,S002,I0003,4,80
B0003,1,2026-10-12,S002,I0004,1,90
B0004,1,2026-10-12,S003,I0005,2,700
CSV
cat > "$ST_WORK/orders_20261012_fixed.csv" <<CSV
$H
B0001,1,2026-10-12,S001,I0001,2,500
B0001,2,2026-10-12,S001,I0002,7,1200
B0002,1,2026-10-12,S002,I0001,3,500
B0003,1,2026-10-12,S002,I0003,4,80
B0003,2,2026-10-12,S002,I0004,1,90
B0004,1,2026-10-12,S003,I0005,2,700
CSV

# No.3: 2026-10-13。500明細（チャンク100で5チャンク）
"$here/gen_orders.sh" 2026-10-13 500 "$ST_WORK/orders_20261013.csv" 5

# No.4: 2026-10-14。二重起動の試行と重なる程度の件数
"$here/gen_orders.sh" 2026-10-14 30000 "$ST_WORK/orders_20261014.csv" 10

# No.5: ヘッダ不正（列名違い）。対象日 2026-10-15
cat > "$ST_WORK/orders_20261015_badheader.csv" <<CSV
order_no,line_no,order_date,store_code,item_code,qty,unit_price
C0001,1,2026-10-15,S001,I0001,2,500
CSV
